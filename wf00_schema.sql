-- ---------- Sequences ----------
CREATE SEQUENCE IF NOT EXISTS order_id_seq;

-- ---------- Helper functions ----------
CREATE OR REPLACE FUNCTION fn_set_updated_at() RETURNS trigger AS $fn$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_orders_enforce_status_transitions() RETURNS trigger AS $fn$
BEGIN
  IF NEW.order_status IS DISTINCT FROM OLD.order_status THEN
    IF NOT (
      (OLD.order_status = 'draft'      AND NEW.order_status IN ('confirmed', 'cancelled')) OR
      (OLD.order_status = 'confirmed'  AND NEW.order_status IN ('processing', 'cancelled')) OR
      (OLD.order_status = 'processing' AND NEW.order_status IN ('shipped', 'cancelled')) OR
      (OLD.order_status = 'shipped'    AND NEW.order_status = 'delivered')
    ) THEN
      RAISE EXCEPTION 'Invalid order_status transition: % -> %', OLD.order_status, NEW.order_status;
    END IF;
  END IF;

  IF NEW.payment_status IS DISTINCT FROM OLD.payment_status THEN
    IF NOT (
      (OLD.payment_status = 'pending' AND NEW.payment_status IN ('paid', 'failed')) OR
      (OLD.payment_status = 'failed'  AND NEW.payment_status IN ('pending', 'paid')) OR
      (OLD.payment_status = 'paid'    AND NEW.payment_status = 'refunded')
    ) THEN
      RAISE EXCEPTION 'Invalid payment_status transition: % -> %', OLD.payment_status, NEW.payment_status;
    END IF;
  END IF;

  RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

-- ---------- 1. products (one row per sellable size/variant) ----------
CREATE TABLE IF NOT EXISTS products (
  product_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku            TEXT         NOT NULL CHECK (btrim(sku) <> ''),
  product_name   TEXT         NOT NULL CHECK (btrim(product_name) <> ''),
  category       TEXT,
  description    TEXT,
  scent_notes    TEXT,
  size_ml        INTEGER      CHECK (size_ml IS NULL OR size_ml > 0),
  price_bdt      NUMERIC(12,2) CHECK (price_bdt IS NULL OR price_bdt >= 0),
  stock_quantity INTEGER      NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  image_url      TEXT,
  active         BOOLEAN      NOT NULL DEFAULT TRUE,
  auto_publish   BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_products_sku_ci        ON products (upper(sku));
CREATE INDEX        IF NOT EXISTS idx_products_active_cat   ON products (active, category);
CREATE INDEX        IF NOT EXISTS idx_products_name_lower   ON products (lower(product_name));

-- ---------- 2. customers ----------
CREATE TABLE IF NOT EXISTS customers (
  customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform         TEXT        NOT NULL CHECK (platform IN ('facebook', 'instagram')),
  platform_user_id TEXT        NOT NULL CHECK (btrim(platform_user_id) <> ''),
  customer_name    TEXT,
  phone            TEXT,
  address          TEXT,
  consent_status   TEXT        NOT NULL DEFAULT 'unknown' CHECK (consent_status IN ('unknown', 'opted_in', 'opted_out')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_customers_platform_user UNIQUE (platform, platform_user_id)
);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers (phone) WHERE phone IS NOT NULL;

-- ---------- 3. conversations ----------
CREATE TABLE IF NOT EXISTS conversations (
  conversation_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id              BIGINT      NOT NULL REFERENCES customers (customer_id) ON DELETE RESTRICT,
  platform                 TEXT        NOT NULL CHECK (platform IN ('facebook', 'instagram')),
  platform_conversation_id TEXT,
  last_message_at          TIMESTAMPTZ,
  status                   TEXT        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'human_handover', 'resolved', 'closed')),
  order_state              TEXT        NOT NULL DEFAULT 'none' CHECK (order_state IN ('none', 'collecting', 'awaiting_confirmation', 'confirmed', 'cancelled')),
  assigned_agent           TEXT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_conversations_platform_conv UNIQUE (platform, platform_conversation_id)
);
CREATE INDEX        IF NOT EXISTS idx_conversations_customer      ON conversations (customer_id);
CREATE INDEX        IF NOT EXISTS idx_conversations_last_message  ON conversations (last_message_at DESC);
CREATE INDEX        IF NOT EXISTS idx_conversations_status        ON conversations (status);
CREATE UNIQUE INDEX IF NOT EXISTS uq_conversations_one_active_per_customer
  ON conversations (customer_id) WHERE status IN ('open', 'human_handover');

-- ---------- 4. messages ----------
CREATE TABLE IF NOT EXISTS messages (
  message_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id     BIGINT      NOT NULL REFERENCES conversations (conversation_id) ON DELETE RESTRICT,
  platform            TEXT        NOT NULL CHECK (platform IN ('facebook', 'instagram')),
  direction           TEXT        NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  sender_id           TEXT,
  message_text        TEXT,
  attachment_url      TEXT,
  intent              TEXT,
  processing_status   TEXT        NOT NULL DEFAULT 'received' CHECK (processing_status IN ('received', 'processed', 'sent', 'failed', 'skipped')),
  platform_message_id TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX        IF NOT EXISTS idx_messages_conversation_created ON messages (conversation_id, created_at);
CREATE INDEX        IF NOT EXISTS idx_messages_created_at           ON messages (created_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_messages_platform_message_id
  ON messages (platform, platform_message_id) WHERE platform_message_id IS NOT NULL;

-- ---------- 5. webhook_events ----------
CREATE TABLE IF NOT EXISTS webhook_events (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform          TEXT        NOT NULL CHECK (platform IN ('facebook', 'instagram')),
  external_event_id TEXT        NOT NULL CHECK (btrim(external_event_id) <> ''),
  event_type        TEXT        NOT NULL CHECK (btrim(event_type) <> ''),
  payload_hash      TEXT,
  processing_status TEXT        NOT NULL DEFAULT 'received' CHECK (processing_status IN ('received', 'processing', 'processed', 'ignored', 'invalid', 'failed')),
  received_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at      TIMESTAMPTZ,
  error_message     TEXT,
  CONSTRAINT uq_webhook_events_scope UNIQUE (platform, event_type, external_event_id)
);
CREATE INDEX IF NOT EXISTS idx_webhook_events_received  ON webhook_events (received_at);
CREATE INDEX IF NOT EXISTS idx_webhook_events_status    ON webhook_events (processing_status, received_at);
CREATE INDEX IF NOT EXISTS idx_webhook_events_hash      ON webhook_events (payload_hash) WHERE payload_hash IS NOT NULL;

-- ---------- 6. orders ----------
CREATE TABLE IF NOT EXISTS orders (
  order_id        TEXT PRIMARY KEY DEFAULT (
                    'ORD-' || to_char((now() AT TIME ZONE 'Asia/Dhaka'), 'YYMMDD') || '-' ||
                    lpad(nextval('order_id_seq')::text, 6, '0')
                  ),
  customer_id     BIGINT        NOT NULL REFERENCES customers (customer_id) ON DELETE RESTRICT,
  conversation_id BIGINT        REFERENCES conversations (conversation_id) ON DELETE RESTRICT,
  platform        TEXT          NOT NULL CHECK (platform IN ('facebook', 'instagram')),
  customer_name   TEXT,
  phone           TEXT,
  address         TEXT,
  subtotal_bdt    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal_bdt >= 0),
  delivery_fee_bdt NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee_bdt >= 0),
  total_bdt       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_bdt >= 0),
  payment_method  TEXT,
  payment_status  TEXT          NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded')),
  order_status    TEXT          NOT NULL DEFAULT 'draft'   CHECK (order_status IN ('draft', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled')),
  source          TEXT          NOT NULL DEFAULT 'chat',
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
  confirmed_at    TIMESTAMPTZ,
  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT chk_orders_total_math CHECK (total_bdt = subtotal_bdt + delivery_fee_bdt),
  CONSTRAINT chk_orders_confirmed_needs_timestamp CHECK (order_status IN ('draft', 'cancelled') OR confirmed_at IS NOT NULL),
  CONSTRAINT chk_orders_confirmed_needs_details CHECK (
    order_status IN ('draft', 'cancelled')
    OR (customer_name IS NOT NULL AND phone IS NOT NULL AND address IS NOT NULL AND payment_method IS NOT NULL)
  )
);
CREATE INDEX        IF NOT EXISTS idx_orders_customer         ON orders (customer_id);
CREATE INDEX        IF NOT EXISTS idx_orders_conversation     ON orders (conversation_id);
CREATE INDEX        IF NOT EXISTS idx_orders_status_created   ON orders (order_status, created_at);
CREATE INDEX        IF NOT EXISTS idx_orders_payment_status   ON orders (payment_status);
CREATE INDEX        IF NOT EXISTS idx_orders_confirmed_at     ON orders (confirmed_at) WHERE confirmed_at IS NOT NULL;
CREATE INDEX        IF NOT EXISTS idx_orders_phone            ON orders (phone) WHERE phone IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_orders_one_draft_per_conversation
  ON orders (conversation_id) WHERE order_status = 'draft' AND conversation_id IS NOT NULL;

-- ---------- 7. order_items ----------
CREATE TABLE IF NOT EXISTS order_items (
  order_item_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id              TEXT          NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
  product_id            BIGINT        NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
  sku                   TEXT          NOT NULL,
  product_name_snapshot TEXT          NOT NULL,
  size_ml               INTEGER       CHECK (size_ml IS NULL OR size_ml > 0),
  unit_price_bdt        NUMERIC(12,2) NOT NULL CHECK (unit_price_bdt >= 0),
  quantity              INTEGER       NOT NULL CHECK (quantity > 0),
  line_total_bdt        NUMERIC(12,2) NOT NULL CHECK (line_total_bdt >= 0),
  CONSTRAINT chk_order_items_line_math CHECK (line_total_bdt = unit_price_bdt * quantity),
  CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_order_items_order   ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items (product_id);

-- ---------- 8. faqs ----------
CREATE TABLE IF NOT EXISTS faqs (
  faq_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category   TEXT,
  question   TEXT        NOT NULL CHECK (btrim(question) <> ''),
  answer     TEXT        NOT NULL CHECK (btrim(answer) <> ''),
  active     BOOLEAN     NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_faqs_active_category ON faqs (active, category);

-- ---------- 9. store_settings ----------
CREATE TABLE IF NOT EXISTS store_settings (
  setting_key   TEXT PRIMARY KEY CHECK (btrim(setting_key) <> ''),
  setting_value TEXT        NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- 10. content_queue ----------
CREATE TABLE IF NOT EXISTS content_queue (
  content_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_file_id    TEXT,
  file_hash         TEXT,
  product_id        BIGINT      REFERENCES products (product_id) ON DELETE RESTRICT,
  channel           TEXT        NOT NULL CHECK (channel IN ('facebook', 'instagram')),
  caption           TEXT,
  hashtags          TEXT,
  status            TEXT        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'review', 'approved', 'rejected', 'publishing', 'published', 'failed')),
  approval_required BOOLEAN     NOT NULL DEFAULT TRUE,
  approved_by       TEXT,
  approved_at       TIMESTAMPTZ,
  external_post_id  TEXT,
  permalink         TEXT,
  error_message     TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at      TIMESTAMPTZ,
  CONSTRAINT chk_content_published_needs_api_id CHECK (status <> 'published' OR (external_post_id IS NOT NULL AND published_at IS NOT NULL)),
  CONSTRAINT chk_content_publish_needs_product  CHECK (status NOT IN ('approved', 'publishing', 'published') OR product_id IS NOT NULL),
  CONSTRAINT chk_content_publish_needs_approval CHECK (status NOT IN ('publishing', 'published') OR approval_required = FALSE OR approved_at IS NOT NULL)
);
CREATE INDEX        IF NOT EXISTS idx_content_queue_status_created ON content_queue (status, created_at);
CREATE INDEX        IF NOT EXISTS idx_content_queue_product        ON content_queue (product_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_content_queue_source_file
  ON content_queue (source_file_id, channel) WHERE source_file_id IS NOT NULL AND status NOT IN ('failed', 'rejected');
CREATE UNIQUE INDEX IF NOT EXISTS uq_content_queue_file_hash
  ON content_queue (file_hash, channel) WHERE file_hash IS NOT NULL AND status NOT IN ('failed', 'rejected');

-- ---------- 11. workflow_errors ----------
CREATE TABLE IF NOT EXISTS workflow_errors (
  error_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_name      TEXT        NOT NULL,
  node_name          TEXT,
  execution_id       TEXT,
  execution_url      TEXT,
  error_message      TEXT,
  related_order_id   TEXT        REFERENCES orders (order_id) ON DELETE SET NULL,
  related_content_id BIGINT      REFERENCES content_queue (content_id) ON DELETE SET NULL,
  retry_count        INTEGER     NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at        TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_workflow_errors_wf_created   ON workflow_errors (workflow_name, node_name, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_workflow_errors_unresolved   ON workflow_errors (created_at) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_workflow_errors_execution    ON workflow_errors (execution_id) WHERE execution_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_workflow_errors_order        ON workflow_errors (related_order_id) WHERE related_order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_workflow_errors_content      ON workflow_errors (related_content_id) WHERE related_content_id IS NOT NULL;

-- ---------- Triggers (created only if missing) ----------
DO $do$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['products', 'customers', 'conversations', 'orders', 'faqs', 'store_settings'] LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_trigger
      WHERE tgname = 'trg_' || t || '_set_updated_at' AND tgrelid = to_regclass(t)
    ) THEN
      EXECUTE format(
        'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at()',
        'trg_' || t || '_set_updated_at', t
      );
    END IF;
  END LOOP;

  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'trg_orders_status_transitions' AND tgrelid = to_regclass('orders')
  ) THEN
    CREATE TRIGGER trg_orders_status_transitions
      BEFORE UPDATE OF order_status, payment_status ON orders
      FOR EACH ROW EXECUTE FUNCTION fn_orders_enforce_status_transitions();
  END IF;
END
$do$;

